def populate_vitals_summary():
    """
    Populate the Patient_Vitals_Summary table with aggregated vital statistics.
    Bulk loads all observations, processes in parallel, bulk writes results.
    """
    import concurrent.futures
    import multiprocessing
    import time
    from collections import defaultdict
    import re
    
    print("\n" + "=" * 60)
    print("📈 Populating Vitals Summary (Bulk Load + Parallel Process)")
    print("=" * 60)
    
    num_cores = multiprocessing.cpu_count()
    print(f"🖥️  Detected {num_cores} CPU cores - will use all for in-memory processing")
    
    start_time = time.time()
    
    vital_codes = {
        'bp_systolic': '8480-6',
        'bp_diastolic': '8462-4',
        'heart_rate': '8867-4',
        'weight': '29463-7',
        'glucose': '2339-0',
    }
    vital_code_set = set(vital_codes.values())
    
    # ========== PHASE 1: BULK LOAD ==========
    print("\n📥 Phase 1: Bulk loading vitals data...")
    phase1_start = time.time()
    
    conn = get_db_connection()
    cursor = conn.cursor(dictionary=True)
    
    # Load patients
    print("   Loading patients...", end=" ", flush=True)
    cursor.execute("SELECT synthea_id, first_name, last_name FROM Synthea_Patient")
    patients = {p['synthea_id']: p for p in cursor.fetchall()}
    print(f"✅ {len(patients)}")
    
    # Load only vitals observations
    print("   Loading vitals observations...", end=" ", flush=True)
    placeholders = ','.join(['%s'] * len(vital_code_set))
    cursor.execute(f"""
        SELECT synthea_patient_id, code, value, observation_date
        FROM Synthea_Observation 
        WHERE code IN ({placeholders}) AND value IS NOT NULL
    """, list(vital_code_set))
    
    obs_by_patient_code = defaultdict(lambda: defaultdict(list))
    obs_count = 0
    numeric_pattern = re.compile(r'^-?[0-9]+\.?[0-9]*$')
    
    for obs in cursor.fetchall():
        # Filter numeric values only
        if obs['value'] and numeric_pattern.match(str(obs['value'])):
            try:
                val = float(obs['value'])
                obs_by_patient_code[obs['synthea_patient_id']][obs['code']].append({
                    'value': val,
                    'date': obs['observation_date']
                })
                obs_count += 1
            except (ValueError, TypeError):
                pass
    print(f"✅ {obs_count} numeric vitals")
    
    cursor.close()
    conn.close()
    
    phase1_time = time.time() - phase1_start
    print(f"   ⏱️  Phase 1 completed in {phase1_time:.2f}s")
    
    # ========== PHASE 2: PARALLEL PROCESSING ==========
    print(f"\n⚡ Phase 2: Computing vitals statistics with {num_cores} cores...")
    phase2_start = time.time()
    
    def process_patient_vitals(patient_id):
        """Compute vital statistics for one patient"""
        patient = patients[patient_id]
        patient_obs = obs_by_patient_code.get(patient_id, {})
        
        result = {
            'synthea_id': patient_id,
            'name': f"{patient['first_name']} {patient['last_name']}",
            'vitals_found': {},
            'data': []
        }
        
        for vital_name, loinc_code in vital_codes.items():
            obs_list = patient_obs.get(loinc_code, [])
            if obs_list:
                values = [o['value'] for o in obs_list]
                dates = [o['date'] for o in obs_list if o['date']]
                
                min_val = min(values)
                max_val = max(values)
                avg_val = sum(values) / len(values)
                first_date = min(dates) if dates else None
                last_date = max(dates) if dates else None
                count = len(values)
                
                result['vitals_found'][vital_name] = count
                result['data'].append((
                    patient_id, vital_name, loinc_code,
                    min_val, max_val, avg_val,
                    first_date, last_date, count
                ))
        
        return result
    
    patient_ids = list(patients.keys())
    results = []
    
    print(f"\n{'#':<5} {'Patient Name':<30} {'BP Sys':<8} {'BP Dia':<8} {'HR':<8} {'Weight':<8} {'Glucose':<8}")
    print("-" * 90)
    
    with concurrent.futures.ThreadPoolExecutor(max_workers=num_cores) as executor:
        future_to_id = {executor.submit(process_patient_vitals, pid): pid for pid in patient_ids}
        
        completed = 0
        for future in concurrent.futures.as_completed(future_to_id):
            completed += 1
            result = future.result()
            results.append(result)
            
            vitals = result['vitals_found']
            bp_s = str(vitals.get('bp_systolic', '-'))
            bp_d = str(vitals.get('bp_diastolic', '-'))
            hr = str(vitals.get('heart_rate', '-'))
            wt = str(vitals.get('weight', '-'))
            gl = str(vitals.get('glucose', '-'))
            
            print(f"{completed:<5} {result['name']:<30} {bp_s:<8} {bp_d:<8} {hr:<8} {wt:<8} {gl:<8}")
            
            if completed % 25 == 0:
                elapsed = time.time() - phase2_start
                rate = completed / elapsed if elapsed > 0 else 0
                print(f"   📊 Progress: {completed}/{len(patient_ids)} | {rate:.1f}/sec")
    
    phase2_time = time.time() - phase2_start
    print(f"\n   ⏱️  Phase 2 completed in {phase2_time:.2f}s")
    
    # ========== PHASE 3: BULK WRITE ==========
    print("\n💾 Phase 3: Bulk writing to database...")
    phase3_start = time.time()
    
    conn = get_db_connection()
    cursor = conn.cursor()
    
    insert_sql = """
        INSERT INTO Patient_Vitals_Summary (
            synthea_patient_id, vital_type, vital_code,
            min_value, max_value, avg_value,
            first_measurement_date, last_measurement_date, measurement_count
        ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON DUPLICATE KEY UPDATE
            min_value = VALUES(min_value), max_value = VALUES(max_value),
            avg_value = VALUES(avg_value),
            first_measurement_date = VALUES(first_measurement_date),
            last_measurement_date = VALUES(last_measurement_date),
            measurement_count = VALUES(measurement_count)
    """
    
    all_data = []
    for r in results:
        all_data.extend(r['data'])
    
    if all_data:
        cursor.executemany(insert_sql, all_data)
        conn.commit()
    
    cursor.close()
    conn.close()
    
    phase3_time = time.time() - phase3_start
    print(f"   ⏱️  Phase 3 completed in {phase3_time:.2f}s")
    
    # ========== SUMMARY ==========
    total_time = time.time() - start_time
    total_vitals = defaultdict(int)
    for r in results:
        for vname, vcount in r['vitals_found'].items():
            total_vitals[vname] += vcount
    
    print("\n" + "=" * 60)
    print("✅ Vitals Summary Complete!")
    print(f"   Total patients: {len(results)}")
    print(f"   Total records written: {len(all_data)}")
    for vital_name, count in total_vitals.items():
        print(f"   {vital_name}: {count} measurements")
    print(f"   Total time: {total_time:.2f}s")
    print("=" * 60)


